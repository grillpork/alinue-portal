/**
 * Deterministic mock dataset for the admin UI.
 * A seeded RNG (not Math.random) keeps server/client output identical, so the
 * tables never hydrate with different numbers. Swap src/services/admin.js to the
 * real API and this file can be deleted without touching a single page.
 */

function mulberry32(seed) {
  let a = seed;
  return function next() {
    a |= 0;
    a = (a + 0x6d2b79f5) | 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

